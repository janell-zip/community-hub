        <div class="tab-panel" data-panel="pvcd" id="pvcd">
            <h2>Paulinian Volunteers for Community Development - UNESCO Club</h2>
            <p class="tagline">Paulinians inspired by St. Paul &amp; impelled by the Love of Christ</p>
            <p>The PVCD-UNESCO Club is an institutional student volunteer arm of SPUP established in 1996 by the CDC, mobilizing students and alumni in community engagement, 
                advocacy, and service-learning rooted in the Paulinian spirit of service and global citizenship. Guided by SPUP's Vision-Mission and the Paulinian 5Cs, 
                it promotes faith-driven service, inclusivity, and sustainability while advancing UNESCO's values in education, peace, and cultural heritage.</p>
            <p>Over the years, PVCD has earned national and international recognition for outstanding volunteerism, including a Regional Award from PNVSCA-NEDA in 2011. 
                In 2012, it was accredited by the UNESCO National Commission of the Philippines, becoming the first accredited UNESCO Club in the St. Paul University System 
                and a repeated awardee as Outstanding UNESCO Club in the Philippines by NAUCP.</p>
