            <h2>SPUP-CARES</h2>
            <p class="tagline">Collaborative Action for Resilient, Empowered, and Sustainable Communities</p>
            <p>SPUP-CARES serves as the umbrella framework that unifies all extension initiatives of 
                the University, aligning academic units, alumni, and partner institutions with SPUP's Vision-Mission
                and the Sustainable Development Goals. It promotes transformative education by integrating service-learning, 
                research, and volunteerism into academic formation, strengthening SPUP's commitment to inclusive development 
                and social responsibility.</p>
            <p>Under the CDC's leadership, SPUP-CARES is implemented as a five-year integrated community extension initiative in 
                Brgy. Malalam-Malacabibi beginning AY 2024-2025, addressing social issues, disaster preparedness, and public health 
                through responsive outreach and participatory action research. It is co-implemented by SNAHS, SBAHM, SASTE, SOM, SITE, 
                the Graduate School, and the Basic Education Unit, ensuring a coordinated and holistic approach to community empowerment 
                and sustainable development.</p>
